import { describe, it, expect } from 'vitest';
import { isSmallTalk } from './ai/rag.js';

describe('Приветствия и благодарности — без поиска в базе знаний', () => {
  it.each([
    'Здравствуйте', 'Привет!', 'Добрый день', 'Добрый вечер!!', 'Сәлеметсіз бе', 'Салем', 'Ассаляму алейкум',
    'Спасибо большое', 'Рахмет', 'Рақмет көп', 'Спасибо, всё понятно', 'Как дела?', 'Hello', 'ок спасибо', '👋 Здравствуйте',
  ])('«%s» — приветствие или благодарность', (t) => expect(isSmallTalk(t)).toBe(true));

  it.each([
    'Да', 'Ок', 'Хорошо', '', '👍', 'Здравствуйте, есть доставка в Астану?', 'Привет, сколько стоят кроссовки?',
    'Добрый день, хочу заказать', 'Спасибо, а размер 42 есть?', 'Сколько стоит доставка',
  ])('«%s» — не приветствие', (t) => expect(isSmallTalk(t)).toBe(false));
});
